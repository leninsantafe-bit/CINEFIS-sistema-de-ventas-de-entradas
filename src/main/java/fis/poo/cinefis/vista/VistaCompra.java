    private void configurarTabla() {
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                // Solo se permite editar la columna Edad
                return column == 1;
            }
        };

        modelo.addColumn("Asiento");
        modelo.addColumn("Edad");
        modelo.addColumn("Tipo cliente");
        modelo.addColumn("Precio");

        tablaEntradas.setModel(modelo);

        // Evita que el usuario mueva las columnas
        tablaEntradas.getTableHeader().setReorderingAllowed(false);
    }

    private void cargarAsientos(ArrayList<String> asientosSeleccionados) {
        DefaultTableModel modelo = (DefaultTableModel) tablaEntradas.getModel();

        for (String asiento : asientosSeleccionados) {
            modelo.addRow(new Object[]{asiento, "", "", ""});
        }
    }      
    
    //Obtener cantidad de entradas
    public int obtenerCantidadEntradas() {
        return tablaEntradas.getRowCount();
    }
    
    //Obtener asiento de una fila
    public String obtenerAsiento(int fila) {
        Object valor = tablaEntradas.getValueAt(fila, 0);
        if (valor == null) {
            return "";
        }
        return valor.toString().trim();
    }
    
    //Obtener la edad escrita
    public String obtenerEdad(int fila) {
        Object valor = tablaEntradas.getValueAt(fila, 1);
        if (valor == null) {
            return "";
        }
        return valor.toString().trim();
    }
    
    //Mostrar el resultado calculado
    public void mostrarResultadoEntrada(int fila, String tipoCliente, double precio) {
        tablaEntradas.setValueAt(tipoCliente, fila, 2);
        tablaEntradas.setValueAt(
                String.format("$%.2f", precio),
                fila,
                3
        );
    }
    
    //Limpiar resultados anteriores
    public void limpiarResultadosEntradas() {
        for (int fila = 0; fila < tablaEntradas.getRowCount(); fila++) {
            tablaEntradas.setValueAt("", fila, 2);
            tablaEntradas.setValueAt("", fila, 3);
        }
        mostrarTotales(0, 0, 0);
    }
    
    //mostrar totales
    public void mostrarTotales(double subtotalEntradas, double subtotalSnacks, double total) {
        lblSubtotalEntradas.setText(
                String.format(
                        "Subtotal entradas: $%.2f",
                        subtotalEntradas
                )
        );
        lblSubtotalSnacks.setText(
                String.format(
                        "Subtotal snacks: $%.2f",
                        subtotalSnacks
                )
        );
        lblTotal.setText(
                String.format(
                        "Total: $%.2f",
                        total
                )
        );
    }
    
