    private void configurarEventosSnacks() {
        chkCanguil.addActionListener(e -> {
            if (chkCanguil.isSelected() && (int) spnCanguil.getValue() == 0) {
                spnCanguil.setValue(1);
            }

            if (!chkCanguil.isSelected()) {
                spnCanguil.setValue(0);
            }
        });

        chkGaseosa.addActionListener(e -> {
            if (chkGaseosa.isSelected() && (int) spnGaseosa.getValue() == 0) {
                spnGaseosa.setValue(1);
            }

            if (!chkGaseosa.isSelected()) {
                spnGaseosa.setValue(0);
            }
        });

        chkNachos.addActionListener(e -> {
            if (chkNachos.isSelected() && (int) spnNachos.getValue() == 0) {
                spnNachos.setValue(1);
            }

            if (!chkNachos.isSelected()) {
                spnNachos.setValue(0);
            }
        });
    }
    
